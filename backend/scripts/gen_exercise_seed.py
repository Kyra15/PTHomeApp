"""Generate the exercise-library seed migration from shared/exercise-library.json.

    python backend/scripts/gen_exercise_seed.py

Writes backend/supabase/migrations/0007_seed_exercise_library.sql. The SQL upserts on `slug`, so it is
safe to re-run in the Supabase SQL editor after editing the JSON (existing plans keep pointing at the
same exercise rows).
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "shared" / "exercise-library.json"
OUT = ROOT / "backend" / "supabase" / "migrations" / "0007_seed_exercise_library.sql"

COLUMNS = [
    "slug", "name", "body_area", "description", "instructions", "positioning_tip", "sensor_mode", "diagram",
    "default_sets", "default_reps", "target_angle_deg", "return_angle_deg", "target_rotation_deg",
    "est_minutes", "difficulty", "equipment", "tags", "accent_color",
]


def lit(value, col):
    if value is None:
        return "null"
    if col == "instructions":
        return "'" + json.dumps(value).replace("'", "''") + "'::jsonb"
    if col == "tags":
        return "array[" + ", ".join("'" + t.replace("'", "''") + "'" for t in value) + "]::text[]"
    if isinstance(value, (int, float)):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def main():
    data = json.loads(SRC.read_text())
    rows = []
    for ex in data["exercises"]:
        rows.append("  (" + ", ".join(lit(ex.get(c), c) for c in COLUMNS) + ")")
    updates = ",\n  ".join(f"{c} = excluded.{c}" for c in COLUMNS if c != "slug")
    sql = (
        "-- GENERATED by backend/scripts/gen_exercise_seed.py from shared/exercise-library.json — do not edit by hand.\n"
        f"-- Seeds the {len(rows)}-exercise library (F11). Upserts on slug, so it is safe to re-run.\n\n"
        f"insert into public.exercises ({', '.join(COLUMNS)}) values\n"
        + ",\n".join(rows)
        + f"\non conflict (slug) do update set\n  {updates},\n  active = true;\n"
    )
    OUT.write_text(sql)
    print(f"wrote {OUT.relative_to(ROOT)} ({len(rows)} exercises)")


if __name__ == "__main__":
    main()
