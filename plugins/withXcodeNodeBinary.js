// Expo config plugin: fixes the most common "Command PhaseScriptExecution failed with a nonzero exit code".
//
// Xcode runs its build scripts (bundling JS, generating app.config, Hermes setup) WITHOUT your terminal's PATH,
// so a Node installed with nvm / Homebrew / Volta often isn't found and the script phase fails. On every
// `expo prebuild` / `expo run:ios`, this writes ios/.xcode.env.local pointing NODE_BINARY at the exact Node
// that ran the command (Xcode sources that file after ios/.xcode.env). It also warns about spaces in the
// project path, which break some React Native build scripts.
const fs = require('fs');
const path = require('path');
const { withDangerousMod } = require('expo/config-plugins');

module.exports = function withXcodeNodeBinary(config) {
  return withDangerousMod(config, [
    'ios',
    async (cfg) => {
      const iosDir = cfg.modRequest.platformProjectRoot;
      const file = path.join(iosDir, '.xcode.env.local');
      fs.writeFileSync(
        file,
        `# Generated by plugins/withXcodeNodeBinary.js — the Node that ran expo prebuild / run:ios.\n` +
          `export NODE_BINARY="${process.execPath}"\n`,
      );
      if (/\s/.test(cfg.modRequest.projectRoot)) {
        console.warn(
          `\n⚠️  The project folder path contains a space:\n   ${cfg.modRequest.projectRoot}\n` +
            `   Some iOS build scripts fail on paths with spaces ("PhaseScriptExecution failed").\n` +
            `   Move the repo to a path without spaces, e.g. ~/code/PTHomeApp, then run: npm run ios:clean\n`,
        );
      }
      return cfg;
    },
  ]);
};
